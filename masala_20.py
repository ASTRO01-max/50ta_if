# Savol: 1-7 raqamiga mos hafta kunini chiqaring.
# Yechim: Har bir raqamni hafta kuni bilan moslang.
kun = int(input("Hafta kuni raqami (1-7): "))
if kun == 1:
    print("Dushanba")
elif kun == 2:
    print("Seshanba")
elif kun == 3:
    print("Chorshanba")
elif kun == 4:
    print("Payshanba")
elif kun == 5:
    print("Juma")
elif kun == 6:
    print("Shanba")
elif kun == 7:
    print("Yakshanba")
else:
    print("Noto'g'ri raqam")
